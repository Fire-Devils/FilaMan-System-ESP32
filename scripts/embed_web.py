# PlatformIO pre-build script: embeds data/* into the firmware as
# src/generated/web_assets.h (PROGMEM arrays). Python 3 standard library only.
#
# - static files are stored gzip-compressed (if that makes them smaller)
# - pages served through templateProcessor (TEMPLATE_FILES) stay uncompressed,
#   because the processor replaces %placeholders% on the fly
Import("env")
import gzip
import os

TEMPLATE_FILES = {"waage.html", "setup.html"}   # keep in sync with website.cpp (templateProcessor)
SKIP_FILES = {"version.txt"}                    # version is served directly from VERSION

MIME = {
    ".html": "text/html",
    ".css": "text/css",
    ".js": "application/javascript",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".svg": "image/svg+xml",
    ".json": "application/json",
    ".txt": "text/plain",
}


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 24]))
    body = ",\n".join(lines) if lines else "  0x00"
    return "static const uint8_t %s[] PROGMEM = {\n%s\n};\n" % (name, body)


def generate(project_dir):
    data_dir = os.path.join(project_dir, "data")
    out_dir = os.path.join(project_dir, "src", "generated")
    out_file = os.path.join(out_dir, "web_assets.h")

    out = ["// AUTO-GENERATED by scripts/embed_web.py - do not edit, not tracked in git.\n",
           "#pragma once\n#include <Arduino.h>\n\n",
           "struct WebAsset {\n  const char* path;\n  const char* mime;\n  const uint8_t* data;\n"
           "  size_t len;\n  bool gzip;\n  bool tmpl;\n};\n\n"]
    entries = []
    for idx, fname in enumerate(sorted(os.listdir(data_dir))):
        fpath = os.path.join(data_dir, fname)
        if fname.startswith(".") or fname in SKIP_FILES or not os.path.isfile(fpath):
            continue
        with open(fpath, "rb") as f:
            raw = f.read()
        ext = os.path.splitext(fname)[1].lower()
        mime = MIME.get(ext, "application/octet-stream")
        tmpl = fname in TEMPLATE_FILES
        payload, gz = raw, False
        if not tmpl:
            packed = gzip.compress(raw, 9, mtime=0)
            if len(packed) < len(raw):
                payload, gz = packed, True
        var = "web_asset_%d" % idx
        out.append(c_array(var, payload))
        entries.append('  {"/%s", "%s", %s, %d, %s, %s},\n' % (
            fname, mime, var, len(payload), "true" if gz else "false", "true" if tmpl else "false"))
    out.append("\nstatic const WebAsset WEB_ASSETS[] = {\n" + "".join(entries) + "};\n")
    out.append("static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);\n")
    content = "".join(out)

    os.makedirs(out_dir, exist_ok=True)
    try:
        with open(out_file, "r") as f:
            if f.read() == content:
                return  # unchanged: avoid needless rebuilds
    except OSError:
        pass
    with open(out_file, "w") as f:
        f.write(content)
    print("embed_web: wrote %s (%d assets)" % (out_file, len(entries)))


generate(env.subst("$PROJECT_DIR"))
